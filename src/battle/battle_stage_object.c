void BattleStageObjectInit(void) {
	BattleUnit* unit;
	BattleStageData* stage;
	BattleStageObjectData* nozzle;
	s32 count;
	BattleStageObjectData* data;
	s32 id;
	s32 layer0 = 0;
	s32 i;
	s32 layer1 = 0;
	BattleWork* wp;
	BattleWorkField180C0* base;
	s32 layer2 = 0;
	s32 layer3 = 0;
	s32 k;
	BattleStageObject* obj;
	BattleStageObjectData* light;
	BOOL hasLayer6 = FALSE;

	wp = _battleWorkPointer;
	base = &wp->field_180C0;
	stage = *(BattleStageData**)wp->fbatInfo->setup;
	count = stage->mNumObjects;
	data = stage->mObjects;
	memset(wp->stageObjects, 0, sizeof(wp->stageObjects));

	switch (pouchGetPtr()->rank) {
	case 1:
	case 2:
	case 3:
		mapPlayAnimationLv(BSO_STR_DEN, 1, 0);
		break;
	}
	switch (pouchGetPtr()->rank) {
	case 1:
	case 2:
	case 3:
		base->field_0x34 = (u8*)battle_stage_nozzle_data + pouchGetPtr()->rank * 0x310;
		break;
	default:
		base->field_0x34 = NULL;
		break;
	}
	base->field_0x38 = (u8*)battle_stage_fall_object_data + pouchGetPtr()->rank * 0x78C;
	base->field_0x1CA = -1;
	base->field_0x1DC = 0;
	base->field_0x1E0 = NULL;

	mapGrpFlagOff(mapGetWork()->entries[0].rootMapObj->joints->name, 2);
	if (mapGetMapObj(BSO_STR_A1) != NULL) {
		mapGrpFlagOn(BSO_STR_A1, 1);
		mapGrpFlagOff(BSO_STR_A1, 2);
	}
	if (mapGetMapObj(BSO_STR_A2) != NULL) {
		mapGrpFlagOn(BSO_STR_A2, 1);
		mapGrpFlagOff(BSO_STR_A2, 2);
	}
	if (mapGetMapObj(BSO_STR_B) != NULL) {
		mapGrpFlagOn(BSO_STR_B, 1);
		mapGrpFlagOff(BSO_STR_B, 2);
	}
	if (mapGetMapObj(BSO_STR_C) != NULL) {
		mapGrpFlagOn(BSO_STR_C, 1);
		mapGrpFlagOff(BSO_STR_C, 2);
	}
	mapGrpFlagOn(BSO_STR_ESCAPE_WALL, 1);

	// the stage's own objects
	id = 1;
	if (data != NULL) {
		for (; count != 0; id++, count--, data++) {
			for (i = 0; i < 32; i++) {
				obj = &wp->stageObjects[i];
				if (obj->id <= 0) {
					break;
				}
			}
			if (i >= 32) {
				break;
			}
			obj->data = data;
			obj->id = id;
			obj->mBattleUnitIdx = -1;
			switch (obj->data->mLayer) {
			case 0: layer0++; break;
			case 1: layer1++; break;
			case 2: layer2++; break;
			case 3: layer3++; break;
			case 6: hasLayer6 = TRUE; break;
			}
			switch (obj->data->mLayer) {
			case 0:
			case 1:
			case 6:
			case 7:
				obj->mPosition = data->mPosition;
				break;
			case 2:
			case 3:
				obj->mPosition = data->mPosition;
				break;
			}
			obj->mRotation.x = obj->mRotation.y = obj->mRotation.z = 0.0f;
			obj->mLastPosition = BSO_UNSET(0);
			obj->mLastPositionOffset1 = BSO_UNSET(1);
			obj->mLastRotation = BSO_UNSET(2);
			obj->mLastPositionOffset2 = BSO_UNSET(3);
			mapGrpFlagOff(obj->data->name, 1);
			switch (data->mSpawnSpecialUnitType) {
			case BSO_SPAWN_TREE:
				unit = BtlUnit_Entry((BattleUnitSetup*)_entry_tree_data);
				unit->stageObjectId = obj->id;
				obj->mBattleUnitIdx = unit->unitId;
				BtlUnit_SetPos(unit, obj->mPosition.x, obj->mPosition.y, obj->mPosition.z);
				BtlUnit_SetHomePos(unit, obj->mPosition.x, obj->mPosition.y, obj->mPosition.z);
				break;
			case BSO_SPAWN_SWITCH:
				unit = BtlUnit_Entry((BattleUnitSetup*)_entry_switch_data);
				unit->stageObjectId = obj->id;
				obj->mBattleUnitIdx = unit->unitId;
				BtlUnit_SetPos(unit, obj->mPosition.x, obj->mPosition.y, obj->mPosition.z);
				BtlUnit_SetHomePos(unit, obj->mPosition.x, obj->mPosition.y, obj->mPosition.z);
				break;
			case BSO_SPAWN_NONE:
				break;
			}
		}
	}

	// the rank's three nozzles
	if (pouchGetPtr()->rank > 0) {
		nozzle = (BattleStageObjectData*)_object_nozzle_data;
		for (k = 0; k < 3; k++, id++, nozzle++) {
			for (i = 0; i < 32; i++) {
				obj = &wp->stageObjects[i];
				if (obj->id <= 0) {
					break;
				}
			}
			if (i >= 32) {
				break;
			}
			obj->data = nozzle;
			obj->id = id;
			obj->mBattleUnitIdx = -1;
			obj->mPosition = nozzle->mPosition;
			obj->mRotation.x = obj->mRotation.y = obj->mRotation.z = 0.0f;
			obj->mLastPosition = BSO_UNSET(4);
			obj->mLastPositionOffset1 = BSO_UNSET(5);
			obj->mLastRotation = BSO_UNSET(6);
			obj->mLastPositionOffset2 = BSO_UNSET(7);
			mapGrpFlagOff(obj->data->name, 1);
		}
	}

	// the escape wall, at the stage's wall height
	data = (BattleStageObjectData*)_object_wall_data;
	for (i = 0; i < 32; i++) {
		obj = &wp->stageObjects[i];
		if (obj->id <= 0) {
			break;
		}
	}
	obj->data = data;
	obj->id = id;
	obj->mBattleUnitIdx = -1;
	obj->mPosition = data->mPosition;
	obj->mPosition.y = BattleStageGetPtr()->stageSize.y;
	obj->mRotation.x = obj->mRotation.y = obj->mRotation.z = 0.0f;
	obj->mLastPosition = BSO_UNSET(8);
	obj->mLastPositionOffset1 = BSO_UNSET(9);
	obj->mLastRotation = BSO_UNSET(10);
	obj->mLastPositionOffset2 = BSO_UNSET(11);
	mapGrpFlagOn(obj->data->name, 1);
	obj->mFlags |= BSO_FLAG_HIDDEN;
	id++;

	// the spotlights, up to the entry with no name
	for (k = 0;; id++, k++) {
		light = &((BattleStageObjectData*)_object_spot_light_data)[k];
		if (light->name == NULL) {
			break;
		}
		for (i = 0; i < 32; i++) {
			obj = &wp->stageObjects[i];
			if (obj->id <= 0) {
				break;
			}
		}
		obj->data = light;
		obj->id = id;
		obj->mBattleUnitIdx = -1;
		obj->mPosition = light->mPosition;
		obj->mRotation.x = obj->mRotation.y = obj->mRotation.z = 0.0f;
		obj->mLastPosition = BSO_UNSET(12);
		obj->mLastPositionOffset1 = BSO_UNSET(13);
		obj->mLastRotation = BSO_UNSET(14);
		obj->mLastPositionOffset2 = BSO_UNSET(15);
		mapGrpFlagOn(obj->data->name, 1);
		obj->mFlags |= BSO_FLAG_HIDDEN;
	}

	// the stage's events; each layer with objects gets its own
	if (stage->initEvent != NULL) {
		evtEntry(stage->initEvent, 10, 0);
	}
	if (layer0 != 0 && stage->layerEvents[0] != NULL) {
		wp->field_180C0.field_0x24 = evtEntry(stage->layerEvents[0], 10, 0)->eventId;
	}
	if (layer1 != 0 && stage->layerEvents[1] != NULL) {
		wp->field_180C0.field_0x28 = evtEntry(stage->layerEvents[1], 10, 0)->eventId;
	}
	if (layer2 != 0 && stage->layerEvents[2] != NULL) {
		wp->field_180C0.field_0x2C = evtEntry(stage->layerEvents[2], 10, 0)->eventId;
	}
	if (layer3 != 0 && stage->layerEvents[3] != NULL) {
		wp->field_180C0.field_0x30 = evtEntry(stage->layerEvents[3], 10, 0)->eventId;
	}
	if (layer0 == 0) {
		wp->field_180C0.stageFlags |= 2;
	}
	if (layer1 == 0) {
		wp->field_180C0.stageFlags |= 4;
	}
	if (layer2 == 0) {
		wp->field_180C0.stageFlags |= 8;
	}
	if (stage->layerDestroyed[0]) {
		wp->field_180C0.stageFlags |= 2;
	}
	if (stage->layerDestroyed[1]) {
		wp->field_180C0.stageFlags |= 4;
	}
	if (stage->layerDestroyed[2]) {
		wp->field_180C0.stageFlags |= 8;
	}
	if (!hasLayer6) {
		wp->field_180C0.stageFlags |= 0x20;
		mapGrpFlagOn(BSO_STR_IF_BODY, 1);
		mapGrpFlagOn(BSO_STR_IF_WIRE, 1);
	}
}

