		BattleWeapon* d = (BattleWeapon*)dst_;
		BattleWeapon* s = (BattleWeapon*)src_;
		_rate_mix(&d->sleepChance, (u8*)&d->sleepTime, (s8*)&s->sleepChance, (u8*)&s->sleepTime);
