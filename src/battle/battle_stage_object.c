s32 BattleStage_ObjectFallCheck(void) {
	BattleWork* wp = _battleWorkPointer;
	BattleWorkField180C0* w = &wp->field_180C0;
	EventEntry* evt;

	if (wp->flags & 0x1000) {
		return 0;
	}
	evt = evtEntry(_object_fall_event, 10, 0);
	w->field_0x1EC = evt->eventId;
	return evt->eventId;
}

s32 _object_fall_wait(void) {
	BattleWorkField180C0* w = &_battleWorkPointer->field_180C0;

	if (!BattleWaitAllActiveEvtEnd_NoBgSetEndWait(_battleWorkPointer)) {
		return 0;
	}
	if (w->field_0x1D8 != 0) {
		if (evtCheckID(w->field_0x1D8)) {
			return 0;
		}
		w->field_0x1D8 = 0;
	}
	if (w->field_0x1E8 != 0) {
		if (evtCheckID(w->field_0x1E8)) {
			return 0;
		}
		w->field_0x1E8 = 0;
	}
	if (w->field_0x20 != 0) {
		if (evtCheckID(w->field_0x20)) {
			return 0;
		}
		w->field_0x20 = 0;
	}
	return 2;
}

USER_FUNC(_object_fall_attack) {
	s32* args = event->args;
	// Each loop has its own entry/weapon locals; MWCC numbers locals in declaration order and colours
	// the callee-saved registers from that, so this order is what places each local in retail's register.
	s32 outId;
	f32 f31;
	s32 outPartId;
	f32 f30;
	BattleWork* wp;
	s32 j;
	s32 active;
	s32 check;
	BattleWeapon* preWeapon;
	s32 flags;
	s32 dst;
	s32 sum;
	FallObjectEntry* preEntry;
	s32 hitFlags;
	s32 i;
	u8* typeTable;
	FallObjectEntry* entry;
	BattleUnit* unit;
	BattleWeapon* newWeapon;
	BattleUnitPart* part;
	s32 idx;
	s32 flag;
	s32 slot;
	FallObjectEntry* newEntry;
	s16 rand;
	BattleWeapon* weapon;
	s8* alloc;
	s32 k;
	s32 off;
	// Stack objects are declared so MWCC lays them out at the original offsets.
	u8 samplingA[0xACC];
	u8 samplingB[0xACC];
	Vec floorPos;
	Vec spawnPos;
	Vec hitPos;
	Vec pos;

	// `wp` is the BattleWork base; typeTable is its fall-object data table (weights at +0xC0, stats at +0xCC).
	wp = _battleWorkPointer;
	typeTable = wp->field_180C0.field_0x38;
	dst = *args++;
	flag = 0;
	if (isFirstCall) {
		alloc = (s8*)BattleAlloc(0xEC);
		event->userdata[0] = (s32)alloc;
		event->userdata[1] = 0;
		memset(alloc, 0, 0xEC);
		alloc[4] = -1;
		for (idx = 0; idx < 3; idx++) {
			alloc[idx + 1] = -1;
		}
		if (BattleCheckConcluded(wp)) {
			evtSetValue(event, dst, event->userdata[1]);
			return EVT_RETURN_DONE;
		}
		alloc[0] = 1;
		i = 0;
		off = 0;
		while (i < (u8)alloc[0]) {
			newEntry = (FallObjectEntry*)(alloc + 4 + off);
			newEntry->no = i;
			for (slot = 0; slot < 3; slot++) {
				if ((s8)alloc[slot + 1] == -1) {
					break;
				}
			}
			if (slot >= 3) {
				newEntry->type = (s8)alloc[irand(3) + 1];
			} else {
				sum = 0;
				for (j = 0; j < 9; j++) {
					sum += typeTable[0xC0 + j];
				}
				sum = irand(sum);
				newEntry->type = 0;
				while (newEntry->type < 8) {
					sum -= typeTable[0xC0 + (s8)newEntry->type];
					if (sum < 0) {
						break;
					}
					newEntry->type++;
				}
				alloc[slot + 1] = newEntry->type;
			}
			{
				s32 t = newEntry->type;
				newEntry->weapon = *(BattleWeapon*)(typeTable + 0xCC + t * 0xC0);
			}
			if (newEntry->type == 6) {
				if (irand(100) < 0x32) {
					newEntry->weapon.targetClassFlags |= 0x100;
					newEntry->weapon.targetClassFlags &= ~0x200;
				} else {
					newEntry->weapon.targetClassFlags &= ~0x100;
					newEntry->weapon.targetClassFlags |= 0x200;
				}
			}
			newWeapon = &newEntry->weapon;
			newEntry->mode = 0;
			if (pouchGetPtr()->mStarPowersObtained != 0
			    && (BattleAudienceBaseGetPtr()->flags & 0x4000) == 0
			    && newEntry->type != 6 && newEntry->type != 7
			    && ((wp->field_19068.forceFlags & 2) != 0 || irand(100) < 10)) {
				newEntry->mode = 1;
				newEntry->partId = -1;
				newEntry->unitId = BattleAudience_HaitiRandForFallObject();
				flag = 1;
				event->userdata[1] = 1;
			}
			if (newEntry->mode == 0) {
				// BattleWork.alliances[1].attackDirection (0x12).
				BattleSamplingEnemy(samplingA, newWeapon, BattleGetSystemPtr(wp)->unitId, 1,
				                    newWeapon->targetClassFlags, newWeapon->targetPropertyFlags,
				                    (s8)-wp->alliances[1].attackDirection);
				if ((s8)samplingA[0xA6C] <= 0) {
					evtSetValue(event, dst, event->userdata[1]);
					return EVT_RETURN_DONE;
				}
				flag = 1;
				BattleChoiceSamplingEnemy(samplingA, newWeapon->targetWeightingFlags, &outId,
				                          &outPartId);
				newEntry->unitId = outId;
				newEntry->partId = outPartId;
				newEntry->flag14 = 1;
				for (j = i; j >= 0; j--) {
					FallObjectEntry* prev = (FallObjectEntry*)(alloc + 4 + j * 0xE8);
					if (newEntry != prev && prev->mode == 0 && newEntry->unitId == prev->unitId) {
						prev->flag14 = 0;
					}
				}
			}
			i++;
			off += 0xE8;
		}
		if (flag == 0) {
			evtSetValue(event, dst, event->userdata[1]);
			return EVT_RETURN_DONE;
		}
		for (i = 0; i < (u8)alloc[0]; i++) {
			preEntry = (FallObjectEntry*)(alloc + 4 + i * 0xE8);
			preWeapon = &preEntry->weapon;
			if (preEntry->mode != 0) {
				continue;
			}
			flags = 0;
			if (preEntry->flag14 != 0) {
				flags |= 0x100;
			}
			if (preEntry->flag15 != 0) {
				flags |= 0x100000;
			}
			preEntry->index = BattlePreCheckDamage(BattleGetSystemPtr(wp), BattleGetUnitPtr(wp, preEntry->unitId),
			                                    BattleGetUnitPartsPtr(preEntry->unitId, preEntry->partId),
			                                    preWeapon, flags);
			if (preEntry->index == 1 && preEntry->flag14 == 0) {
				rand = irand(0);
				for (k = 0; k < i; k++) {
					FallObjectEntry* prev = (FallObjectEntry*)(alloc + 4 + k * 0xE8);
					if (preEntry->unitId == prev->unitId) {
						prev->timer = rand;
						rand = (s16)((s32)irand(0x16) + (s32)rand + 0x14);
						if (prev->flag14 != 0) {
							prev->flag15 = 1;
						}
					}
				}
			}
		}
	}

	alloc = (s8*)event->userdata[0];
	active = 1;
	for (i = 0; i < (u8)alloc[0]; i++) {
		entry = (FallObjectEntry*)(alloc + 4 + i * 0xE8);
		if (entry->no == -1) {
			continue;
		}
		check = 0;
		active = 0;
		if (entry->mode == 0) {
			unit = BattleGetUnitPtr(wp, entry->unitId);
			part = BattleGetUnitPartsPtr(entry->unitId, entry->partId);
		}
		if (entry->effect == NULL || entry->timer > 0) {
			entry->timer--;
			if (entry->timer > 0) {
				continue;
			}
			switch (entry->mode) {
			case 0:
				BtlUnit_GetHitPos(unit, part, &spawnPos.x, &spawnPos.y, &spawnPos.z);
				f30 = (f32)BtlUnit_GetWidth(unit);
				break;
			case 1:
				spawnPos.x = (f32)((entry->unitId % 20) * 25 - 230);
				spawnPos.y = BattleStageGetPtr()->audienceAreaSize.y;
				spawnPos.z = 0.1f * (f32)(entry->unitId % 20)
				             + (f32)((entry->unitId / 20) * 30 + 115);
				btl_camera_set_mode(0, 6);
				btl_camera_set_moveSpeedLv(0, 2);
				f30 = 0.0f;
				break;
			default:
				spawnPos = (Vec){0.0f, 0.0f, 0.0f};
				f30 = 0.0f;
				break;
			}
			floorPos = spawnPos;
			floorPos.y = BattleGetFloorHeight(wp, floorPos.x, floorPos.y, floorPos.z);
			if (spawnPos.x >= 0.0f) {
				f31 = 90.0f;
			} else {
				f31 = 270.0f;
			}
			switch (entry->index) {
			case 2:
			case 3:
			case 4:
			case 6:
				spawnPos.y = floorPos.y;
				break;
			}
			entry->sfxId = -1;
			entry->counter = 0;
			switch (entry->type) {
			case 0:
				entry->effect = effFallEntry(4, floorPos.x, floorPos.y, 1, floorPos.z, 0x5A, f30,
				                              spawnPos.y - floorPos.y, f31);
				break;
			case 1:
				entry->effect = effFallEntry(5, floorPos.x, floorPos.y, 1, floorPos.z, 0x5A, f30,
				                              spawnPos.y - floorPos.y, f31);
				break;
			case 2:
				entry->effect = effFallEntry(0, floorPos.x, floorPos.y, 0x64, floorPos.z, 0x5A, f30,
				                              spawnPos.y - floorPos.y, f31);
				break;
			case 3:
				entry->effect = effFallEntry(1, floorPos.x, floorPos.y, 1, floorPos.z, 0x5A, f30,
				                              spawnPos.y - floorPos.y, f31);
				break;
			case 4:
				entry->effect = effFallEntry(2, floorPos.x, floorPos.y, 1, 5.0f + floorPos.z,
				                              0x5A, f30, spawnPos.y - floorPos.y, f31);
				break;
			case 8:
				entry->effect = effFallEntry(8, floorPos.x, floorPos.y, 1, floorPos.z, 0x5A, f30,
				                              spawnPos.y - floorPos.y, f31);
				break;
			case 5:
				entry->effect = effFallEntry(3, floorPos.x, floorPos.y, 1, floorPos.z, 0x5A, f30,
				                              spawnPos.y - floorPos.y, f31);
				break;
			case 6:
				if (BtlUnit_GetBelong(unit) == 0) {
					entry->effect = effFallEntry(6, -300.0f, floorPos.y, 1,
					                              15.0f + floorPos.z, 0xB4,
					                              0.0f, 0.0f, f31);
				} else {
					entry->effect = effFallEntry(6, 300.0f, floorPos.y, 1,
					                              15.0f + floorPos.z, 0xB4,
					                              0.0f, 0.0f, f31);
				}
				break;
			case 7:
				entry->effect = effFallEntry(7, floorPos.x, floorPos.y, 1, 5.0f + floorPos.z,
				                              0xB4, f30, spawnPos.y - floorPos.y, f31);
				break;
			}
			continue;
		}
		if (entry->effect != NULL && !effFallCheckHit(entry->effect)) {
			continue;
		}
		weapon = &entry->weapon;
		if (entry->mode == 1) {
			BattleAudience_Case_FallObject_Aud(entry->unitId, entry->type);
			psndSFXOff(entry->sfxId);
			BattleAudience_GetHomePosition(entry->unitId, &hitPos.x, &hitPos.y, &hitPos.z);
			switch (entry->type) {
			case 0:
			case 1:
				psndSFXOn_3D(BSO_SFX("SFX_BTL_STAGE_DAMAGE_TUB1"), &hitPos);
				break;
			case 5:
				break;
			default:
				psndSFXOn_3D(BSO_SFX("SFX_BTL_STAGE_DAMAGE_NORMAL1"), &hitPos);
				break;
			}
		} else {
			BattleAudience_Case_FallObject_Stage();
			if (weapon->targetClassFlags & 0x01000000) {
				BtlUnit_GetHitPos(unit, part, &hitPos.x, &hitPos.y, &hitPos.z);
				hitFlags = 0;
				if (entry->flag14 != 0) {
					hitFlags |= 0x100;
				}
				psndSFXOff(entry->sfxId);
				switch (entry->index) {
				case 2:
				case 3:
				case 4:
				case 6:
					switch (entry->type) {
					case 0:
					case 1:
						psndSFXOn_3D(BSO_SFX("SFX_BTL_STAGE_DAMAGE_TUB1"), &hitPos);
						break;
					case 5:
						break;
					}
					break;
				case 1:
					switch (entry->type) {
					case 0:
					case 1:
						psndSFXOn_3D(BSO_SFX("SFX_BTL_STAGE_DAMAGE_TUB1"), &hitPos);
						break;
					case 5:
						psndSFXOn_3D(BSO_SFX("SFX_REST_CONDITION1"), &hitPos);
						break;
					default:
						psndSFXOn_3D(BSO_SFX("SFX_BTL_STAGE_DAMAGE_NORMAL1"), &hitPos);
						break;
					}
					if (BtlUnit_GetACPossibility(unit) != 0) {
						BattleActionCommandCheckDefence(unit, weapon);
					}
					BattleCheckDamage(BattleGetSystemPtr(wp), unit, part, weapon, hitFlags);
					break;
				}
			} else {
				psndSFXOff(entry->sfxId);
				BattleSamplingEnemy(samplingB, weapon, BattleGetSystemPtr(wp)->unitId, 1,
				                    weapon->targetClassFlags, weapon->targetPropertyFlags,
				                    (s8)-wp->alliances[1].attackDirection);
				if ((s8)samplingB[0xA6C] > 0)
				for (;;) {
					s32 si;
					u8* se;
					s32 res;
					BattleUnit* target;
					if ((s8)samplingB[0xAB7] >= (s8)samplingB[0xA6C]) {
						break;
					}
					si = (s8)samplingB[0xA6D + (s8)samplingB[0xAB7]];
					se = samplingB + 4 + si * 0x24;
					target = BattleGetUnitPtr(wp, *(s16*)(se + 0));
					res = BattlePreCheckDamage(BattleGetSystemPtr(wp), target,
					                           BattleGetUnitPartsPtr(*(s16*)(se + 0), *(s16*)(se + 2)),
					                           weapon, 0x100);
					switch (res) {
					case 2:
					case 4:
						break;
					case 3:
						BtlUnit_GetPos(target, &pos.x, &pos.y, &pos.z);
						if (pos.y < 85.0f) {
							pos.y += 50.0f;
						} else {
							pos.y += -50.0f;
						}
						pos.x -= 45.0f;
						{
							EffectEntry* e = effNiceEntry(6, pos.x, pos.y, pos.z);
							((NiceEffectWork*)e->userdata)->scale = 0.75f;
						}
						target->damagePattern = 0;
						BattleRunHitEvent(target, 0x126);
						break;
					case 6:
						target->damagePattern = 0;
						BattleRunHitEvent(target, 0x127);
						break;
					case 1:
						if (BtlUnit_GetACPossibility(target) != 0 && check <= 0) {
							BattleActionCommandCheckDefence(target, weapon);
							check++;
						}
						BattleCheckDamage(BattleGetSystemPtr(wp), target,
						                  BattleGetUnitPartsPtr(*(s16*)(se + 0), *(s16*)(se + 2)),
						                  weapon, 0x100);
						break;
					}
					samplingB[0xAB7]++;
				}
			}
		}
		entry->no = -1;
	}

	if (!active) {
		return 0;
	}
	BattleFree((void*)event->userdata[0]);
	evtSetValue(event, dst, event->userdata[1]);
	return EVT_RETURN_DONE;
}
