// External event functions referenced by the evt_memcard scripts below.

s32 memcard_code(EventEntry* event, BOOL isFirstCall) {
    s32* args = event->args;
    s32 code = cardGetCode();

    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    evtSetValue(event, args[0], code);
    return EVT_RETURN_DONE;
}

s32 memcard_buf_reset(EventEntry* event, BOOL isFirstCall) {
    cardBufReset();
    return EVT_RETURN_DONE;
}

s32 memcard_slot_watch_begin(EventEntry* event, BOOL isFirstCall) {
    cardSlotWatchBegin();
    return EVT_RETURN_DONE;
}

s32 memcard_slot_changed(EventEntry* event, BOOL isFirstCall) {
    s32* args = event->args;

    if (cardSlotChanged()) {
        evtSetValue(event, args[0], 1);
    } else {
        evtSetValue(event, args[0], 0);
    }
    return EVT_RETURN_DONE;
}

s32 memcard_slot_watch_end(EventEntry* event, BOOL isFirstCall) {
    cardSlotWatchEnd();
    return EVT_RETURN_DONE;
}

s32 memcard_load(EventEntry* event, BOOL isFirstCall) {
    if (isFirstCall) {
        cardBufReset();
        cardReadAll();
    }
    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    return EVT_RETURN_DONE;
}

s32 memcard_format(EventEntry* event, BOOL isFirstCall) {
    if (isFirstCall) {
        cardFormat();
    }
    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    return EVT_RETURN_DONE;
}

s32 memcard_create(EventEntry* event, BOOL isFirstCall) {
    if (isFirstCall) {
        cardCreate();
    }
    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    return EVT_RETURN_DONE;
}

s32 memcard_delete(EventEntry* event, BOOL isFirstCall) {
    s32 slot = evtGetValue(event, event->args[0]) - 1;

    if (isFirstCall) {
        cardErase(slot);
    }
    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    return EVT_RETURN_DONE;
}

s32 memcard_copy(EventEntry* event, BOOL isFirstCall) {
    s32* args = event->args;
    s32 from = evtGetValue(event, args[0]) - 1;
    s32 to = evtGetValue(event, args[1]) - 1;

    if (isFirstCall) {
        cardCopy(from, to);
    }
    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    return EVT_RETURN_DONE;
}

s32 memcard_header_write(EventEntry* event, BOOL isFirstCall) {
    if (isFirstCall) {
        cardWriteHeader();
    }
    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    return EVT_RETURN_DONE;
}

s32 memcard_ipl(EventEntry* event, BOOL isFirstCall) {
    gp->resetType = 2;
    return EVT_RETURN_BLOCK;
}

s32 memcard_file_existance(EventEntry* event, BOOL isFirstCall) {
    s32* args = event->args;
    s32 slot = evtGetValue(event, args[0]) - 1;
    CardData* card = cardGetFilePtr();
    CardSaveSlot* save = &card->saves[slot];

    if (save->data.flags & 1) {
        evtSetValue(event, args[1], 0);
    } else {
        evtSetValue(event, args[1], 1);
    }
    return EVT_RETURN_DONE;
}

s32 memcard_write(EventEntry* event, BOOL isFirstCall) {
    if (isFirstCall) {
        cardWrite(gp->saveSlot);
    }
    if (cardIsExec()) {
        return EVT_RETURN_BLOCK;
    }
    return EVT_RETURN_DONE;
}

