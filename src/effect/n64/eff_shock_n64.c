EffectEntry* effShockN64Entry(s32 type, f32 x, f32 y, f32 z, f32 a5, f32 a6) {
	EffectEntry* effect;
	EffShockData* data;

	effect = effEntry();
	effect->type = "ShockN64";
	effect->count = 1;
	data = __memAlloc(HEAP_EFFECT, sizeof(EffShockData));
	effect->userdata = data;
	effect->callback = effShockMain;

	data->type = type;
	data->field_0x20 = 0;
	data->field_0x1C = 30;
	data->field_0x10 = 0xFF;
	data->field_0x14 = 0xFF;
	data->field_0x18 = 0xFF;
	data->x = x;
	data->y = y;
	data->z = z;

	if (type == 2) {
		data->field_0x24 = 1.0f;
	} else {
		data->field_0x24 = 0.0f;
	}

	data->field_0x28 = 0.5f * a5;
	data->field_0x2C = 0.5f * a6;

	switch (type) {
	case 0:
	case 1:
	case 3:
		data->tev1R = 0xFF;
		data->tev1G = 0xFF;
		data->tev1B = 0;
		data->tev2R = 0xFF;
		data->tev2G = 0xFF;
		data->tev2B = 0xFF;
		break;
	default:
		data->tev1R = 0x46;
		data->tev1G = 0xB4;
		data->tev1B = 0x78;
		data->tev2R = 0xFF;
		data->tev2G = 0xFF;
		data->tev2B = 0xFF;
		break;
	}

	return effect;
}
void effShockMain(EffectEntry* effect) {
	f32 k9 = 0.9f;
	f32 k8 = 0.8f;
	EffShockData* data;
	Vec position2;
	Vec position;
	s32 type;
	s32 life;
	s32 frame;

	data = effect->userdata;
	position = (Vec){ 0.0f, 0.0f, 0.0f };
	position.x = data->x;
	position.y = data->y;
	position.z = data->z;
	position2 = position;

	type = data->type;
	if (data->field_0x1C < 100) {
		data->field_0x1C--;
	}
	data->field_0x20++;
	life = data->field_0x1C;
	if (life < 0) {
		effDelete(effect);
		return;
	}

	frame = data->field_0x20;
	if (type == 2) {
		if (frame <= 20) {
			data->field_0x24 *= 1.1f;
		}
	} else {
		data->field_0x24 += 0.05f * (8.0f - data->field_0x24);
	}

	data->field_0x14 = (s32)((f32)data->field_0x14 * k9);
	if (life < 5) {
		data->field_0x18 = (s32)((f32)data->field_0x18 * k8);
	}

	if (frame > 6) {
		data->field_0x10 -= 13;
		if (data->field_0x10 < 0) {
			data->field_0x10 = 0;
		}
	}

	dispEntry(CAMERA_3D, dispCalcZ(&position2), 2, effShockDisp, effect);
}

