// N64 vertex layout of the shared flowers_v array (14-byte stride).
typedef struct Kemuri4Vertex {
	s16 pos[3];
	s16 tex0[2];
	u8 color[4];
} Kemuri4Vertex;


extern const f32 float_0p0625_8041f32c;
extern const f32 float_0_8041f330;
// .data vertex array of this unit (named after its original symbol).

EffectEntry* effKemuri4N64Entry(s32 type, f32 x, f32 y, f32 z, f32 angleDeg, f32 direction) {
	EffectEntry* effect;
	effKemuri4Data* data;
	f32 angle;
	s32 i;

	effect = effEntry();
	effect->type = "Kemuri4N64";
	effect->count = 1;
	data = __memAlloc(HEAP_EFFECT, sizeof(effKemuri4Data));
	effect->userdata = data;
	effect->callback = effKemuri4Main;

	for (i = 0; i < 1; i++) {
		data->active = 1;
		data->type = type;
		data->field_0x6C = float_0_8041f330;
		data->position.x = x;
		data->position.y = y;
		data->position.z = z;
		data->scaleX = 1.0f;
		data->scaleY = 1.0f;
		data->scaleZ = 1.0f;
		data->field_0x08 = 0xFF;
		data->floating = 1.0f;
		data->driftScale = 5.4f;
		data->spin = (f32)(direction != float_0_8041f330 ? -10 : 10);
		data->swirl = 0.5f;
		data->swirlVelocity = -0.07f;
		data->swirlAccel = 0.003f;
		data->swirlJerk = float_0_8041f330;
		data->lifetime = 15;
		data->rotY = angleDeg;
		data->rotX = float_0_8041f330;
		data->rotZ = float_0_8041f330;
		data->textureIndex = ((rand() % 100) >> 4) & 1;
		angle = reviseAngle(angleDeg + (f32)(direction != float_0_8041f330 ? -90 : 90));
		angle = 6.2831855f * angle / 360.0f;
		data->sinAngle = (f32)sin(angle);
		data->cosAngle = (f32)cos(angle);
	}
	return effect;
}

// Local copy of system.c's inline helper so it inlines here as in the original.
inline Vec initializeVec(Vec* input) {
	Vec temp = { 0.0f, 0.0f, 0.0f };
	temp.x = input->x;
	temp.y = input->y;
	temp.z = input->z;
	return temp;
}

void effKemuri4Main(EffectEntry* effect) {
	effKemuri4Data* data;
	Vec position;
	Mtx rotZ;
	Mtx rotY;
	Mtx rotX;
	Mtx trans;
	Mtx scale;
	s32 i;
	s32 active;

	data = effect->userdata;
	position = initializeVec(&data->position);
	active = 0;

	for (i = 0; i < effect->count; i++, data++) {
		if (data->active == 0) {
			continue;
		}
		if (--data->lifetime <= 0) {
			data->active = 0;
			continue;
		}
		active = 1;

		if (data->type == 0 && data->floating != float_0_8041f330
		    && marioGetPtr()->currMotionId == MARIO_MOTION_STAY) {
			data->lifetime++;
		}
		else {
			data->swirlAccel += data->swirlJerk;
			data->swirlVelocity += data->swirlAccel;
			data->swirl += data->swirlVelocity;
			data->rotZ = data->swirl * data->spin + data->rotZ;
			data->position.x -= data->sinAngle * (data->swirl * data->driftScale);
			data->position.z -= data->cosAngle * (data->swirl * data->driftScale);
			data->field_0x08 -= 12;
			if (data->swirl < float_0_8041f330) {
				data->floating = float_0_8041f330;
			}
		}

		PSMTXRotRad(rotX, 'x', 0.017453292f * data->rotX);
		PSMTXRotRad(rotY, 'y', 0.017453292f * data->rotY);
		PSMTXRotRad(rotZ, 'z', 0.017453292f * data->rotZ);
		PSMTXTrans(trans, data->position.x, data->position.y, data->position.z);
		PSMTXScale(scale, data->scaleX, data->scaleY, data->scaleZ);
		PSMTXConcat(rotX, rotZ, rotZ);
		PSMTXConcat(rotY, rotZ, rotZ);
		PSMTXConcat(rotZ, scale, scale);
		PSMTXConcat(trans, scale, data->matrix);
	}

	if (active == 0) {
		effDelete(effect);
	}
	else {
		dispEntry(CAMERA_3D, dispCalcZ(&position), 1, effKemuri4Disp, effect);
	}
}

void effKemuri4Disp(CameraId camId, void* param) {
	EffectEntry* effect;
	CameraEntry* cam;
	GXTexObj texObj;
	Mtx mtx;
	Mtx texMtx;
	Kemuri4Vertex* vtx0;
	Kemuri4Vertex* vtx1;
	effKemuri4Data* data;
	s32 i;

	effect = param;
	cam = camGetPtr(camId);
	data = effect->userdata;
	GXSetCullMode(0);
	vtx0 = &((Kemuri4Vertex*)flowers_v)[25];
	vtx1 = &((Kemuri4Vertex*)flowers_v)[35];

	for (i = 0; i < effect->count; i++, data++) {
		if (data->active == 0) {
			continue;
		}
		if ((s8)data->textureIndex != 0) {
			effGetTexObjN64(0x4C, &texObj);
		}
		else {
			effGetTexObjN64(0x4D, &texObj);
		}
		GXLoadTexObj(&texObj, 0);
		GXSetNumTexGens(1);
		GXSetTexCoordGen2(0, 1, 4, 0x1E, 0, 0x7D);
		PSMTXScale(texMtx, float_0p0625_8041f32c, float_0p0625_8041f32c, float_0_8041f330);
		GXLoadTexMtxImm(texMtx, 0x1E, 1);
		GXSetNumChans(0);
		GXSetNumTevStages(1);
		GXSetTevOrder(0, 0, 0, 0xFF);
		GXSetTevColorOp(0, 0, 0, 0, 1, 0);
		GXSetTevAlphaOp(0, 0, 0, 0, 1, 0);
		GXSetTevColorIn(0, 0xF, 8, 2, 0xF);
		GXSetTevAlphaIn(0, 7, 4, 1, 7);
		PSMTXConcat(cam->view, data->matrix, mtx);
		GXLoadPosMtxImm(mtx, 0);
		GXSetTevColor(1, (GXColor){ 0xF0, 0xF0, 0xF0, 0xFF });
		effSetVtxDescN64(vtx0);
		GXBegin(0x90, 0, 6);
		tri2(0, 1, 2, 0, 0, 2, 3, 0);
		GXSetNumChans(1);
		GXSetChanCtrl(4, 0, 0, 1, 0, 0, 2);
		GXSetNumTexGens(0);
		GXSetNumTevStages(1);
		GXSetTevOrder(0, 0xFF, 0xFF, 4);
		GXSetTevOp(0, 4);
		effSetVtxDescN64(vtx1);
		GXBegin(0x90, 0, 6);
		tri2(0, 1, 2, 0, 3, 4, 5, 0);
	}
}

