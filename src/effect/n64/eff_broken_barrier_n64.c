EffectEntry* effBrokenBarrierN64Entry(s32 type, s32 life, f32 x, f32 y, f32 z, f32 scale) {
    EffectEntry* entry;
    effBrokenBarrierData* data;
    effBrokenBarrierData* d;
    f32 f6;
    s32 i;

    entry = effEntry();
    entry->type = "BrokenBarrierN64";
    entry->count = 0x3D;
    data = __memAlloc(HEAP_EFFECT, 0x19BC);
    entry->userdata = data;
    entry->callback = effBrokenBarrierMain;
    entry->flags |= 2;
    data->type = type;
    data->field_0x3c = 0;
    if (life <= 0) {
        data->life = 1000;
    } else {
        data->life = life;
    }
    d = data + 1;
    data->field_0x4C = 0xff;
    data->x = x;
    data->y = y;
    data->z = z;
    data->field_0x60 = scale;
    data->field_0x10 = float_30_8041eb08;
    data->field_0x14 = float_30_8041eb08;
    data->field_0x40 = 0xff;
    data->field_0x44 = 0xff;
    data->field_0x48 = 0xff;
    data->field_0x50 = 0xd7;
    data->field_0x54 = 0xff;
    data->field_0x58 = 0xeb;
    data->field_0x5C = 0xff;
    if (life < 20) {
        f6 = float_0p33333_8041eb0c;
    } else {
        f6 = (f32)life / float_60_8041eb10;
    }
    for (i = 1; i < 61; i++, d++) {
        d->field_0x30 = (s32)(-(f32)i * f6) - 1;
    }
    return entry;
}

// Inlined MetroWerks sqrtf (same shape as eff_fire_dust_n64.c / eff_magic3_n64.c).
int __float_nan[];
#define NAN (*(f32*)__float_nan)

#define FP_NAN 1
#define FP_INFINITE 2
#define FP_ZERO 3
#define FP_NORMAL 4
#define FP_SUBNORMAL 5

static inline s32 effBrokenBarrierFpClassify(f32 x) {
    switch (*(s32*)&x & 0x7F800000) {
    case 0x7F800000:
        if (*(s32*)&x & 0x007FFFFF) {
            return FP_NAN;
        }
        else {
            return FP_INFINITE;
        }
    case 0:
        if (*(s32*)&x & 0x007FFFFF) {
            return FP_SUBNORMAL;
        }
        else {
            return FP_ZERO;
        }
    default:
        return FP_NORMAL;
    }
}

#define fpclassify(x) effBrokenBarrierFpClassify(x)
#define isnan(x) (fpclassify(x) == FP_NAN)

static inline f32 effBrokenBarrierSqrt(f32 x) {
    const f64 _half = .5;
    const f64 _three = 3.0;

    if (x > float_0_8041eac8) {
        f64 guess = __frsqrte(x);
        guess = _half * guess * (_three - guess * guess * x);
        guess = _half * guess * (_three - guess * guess * x);
        guess = _half * guess * (_three - guess * guess * x);
        return x * guess;
    }
    else if (x < 0.0) {
        return NAN;
    }
    else if (isnan(x)) {
        return NAN;
    }
    return x;
}

// NONMATCHING (98.47%): body functionally complete; all array/struct accesses, constants, call args and branches
// match. Remaining diffs are FPR allocation only: the first cos(angle2) temp sits in f24 (target reuses f27 for both
// calls), shifting f24..f27 and growing the frame 0xd0->0xe0; `fctiwz`/0.5 swap f1/f2; spread-scale block layout.
void effBrokenBarrierMain(EffectEntry* effect) {
    s32 rangeX;
    s32 rangeY;
    effBrokenBarrierData* data;
    s32 i;
    s32 type;
    Vec position;
    Vec disp = vec3_802fa328;
    f32 halfX;
    f32 halfY;
    f32 spreadX;
    f32 spreadY;
    f32 c2;
    f32 angle2;
    f32 angle1;
    f32 randA;
    f32 randB;

    data = effect->userdata;
    disp.x = data->x;
    disp.y = data->y;
    disp.z = data->z;
    position = disp;
    type = data->type;

    if (effect->flags & 4) {
        effect->flags &= ~4;
        data->life = 0x10;
    }
    if (data->life < 1000) {
        data->life--;
    }
    data->field_0x3c++;
    if (data->life < 0) {
        effDelete(effect);
        return;
    }
    if (data->life < 8) {
        data->field_0x4C = data->life << 5;
    }

    spreadX = data->field_0x10;
    spreadY = data->field_0x14;
    if (type < 4 && type >= 2) {
        spreadX *= float_4_8041ead4;
        spreadY *= float_4_8041ead4;
    }
    i = 1;
    rangeX = (s32)spreadX;
    rangeY = (s32)spreadY;
    halfX = float_0p5_8041ead8 * spreadX;
    halfY = float_0p5_8041ead8 * spreadY;
    data++;
    for (; i < effect->count; i++, data++) {
        data->field_0x30++;
        if (data->field_0x30 >= 0x14) {
            data->field_0x30 = 0;
        }
        if (data->field_0x30 < 0) {
            continue;
        }
        if (data->field_0x30 == 0) {
            randA = (f32)(rand() % 360);
            randB = (f32)(rand() % 360);
            switch (type) {
            case 0:
            case 2:
                angle2 = float_6p2832_8041eadc * randB / float_360_8041eae0;
                c2 = (f32)cos(angle2);
                angle1 = float_6p2832_8041eadc * randA / float_360_8041eae0;
                data->x = spreadX * (f32)sin(angle1) * c2;
                c2 = (f32)cos(angle2);
                data->y = spreadY * (f32)cos(angle1) * c2;
                data->z = spreadX * (f32)sin(angle2);
                data->field_0x18 = float_0p4_8041eae4 * data->x;
                data->field_0x1C = float_0p4_8041eae4 * data->y;
                data->field_0x20 = float_0p4_8041eae4 * data->z;
                data->field_0x24 = float_0p1_8041eae8 * data->field_0x18;
                data->field_0x28 = float_0p1_8041eae8 * data->field_0x1C;
                data->field_0x2C = float_0p1_8041eae8 * data->field_0x20;
                break;
            default:
                data->x = (f32)(rand() % rangeX) - halfX;
                data->y = (f32)(rand() % rangeY) - halfY;
                data->z = (f32)(rand() % rangeX) - halfX;
                data->field_0x18 = float_0p3_8041eaec * data->x;
                data->field_0x1C = float_0p3_8041eaec * data->y;
                data->field_0x20 = float_0p3_8041eaec * data->z;
                data->field_0x24 = float_0p02_8041eaf0 * data->field_0x18;
                data->field_0x28 = float_0p02_8041eaf0 * data->field_0x1C;
                data->field_0x2C = float_0p02_8041eaf0 * data->field_0x20;
                break;
            }
            data->field_0x64 = (f32)(rand() % 15);
            data->field_0x68 = (f32)(rand() % 15);
            data->field_0x34 = float_0_8041eac8;
            data->field_0x4C = 0xff;
        }
        data->field_0x60 = scale_data[data->field_0x30];
        data->field_0x34 += float_4_8041ead4;
        if (type < 4 && type >= 2) {
            data->field_0x18 = float_0p05_8041eaf4 * -data->x;
            data->field_0x1C = float_0p05_8041eaf4 * -data->y;
            data->field_0x20 = float_0p05_8041eaf4 * -data->z;
            if (effBrokenBarrierSqrt(data->field_0x18 * data->field_0x18 + data->field_0x1C * data->field_0x1C + data->field_0x20 * data->field_0x20) < float_1_8041eaf8) {
                randA = (f32)(rand() % 360);
                randB = (f32)(rand() % 360);
                angle2 = float_6p2832_8041eadc * randB / float_360_8041eae0;
                c2 = (f32)cos(angle2);
                angle1 = float_6p2832_8041eadc * randA / float_360_8041eae0;
                data->x = spreadX * (f32)sin(angle1) * c2;
                c2 = (f32)cos(angle2);
                data->y = spreadY * (f32)cos(angle1) * c2;
                data->z = spreadX * (f32)sin(angle2);
            }
        }
        data->x += data->field_0x18;
        data->y += data->field_0x1C;
        data->z += data->field_0x20;
        data->field_0x64 += float_0p2_8041eafc;
        data->field_0x68 += float_0p6_8041eb00;
        data->field_0x18 += float_0p04_8041eb04 * (data->field_0x24 - data->field_0x18);
        data->field_0x1C += float_0p04_8041eb04 * (data->field_0x28 - data->field_0x1C);
        data->field_0x20 += float_0p04_8041eb04 * (data->field_0x2C - data->field_0x20);
    }
    dispEntry(CAMERA_3D, dispCalcZ(&position), 2, effBrokenBarrierDisp, effect);
}

// Builds the particle colour from the shared zero colour; the inline forces mwcc to
// keep the named GXColor at r1+0x8 and its outgoing copy at r1+0xC (the original order).
static inline GXColor effBrokenBarrierMakeColor(u8 r, u8 g, u8 b, u8 a) {
    GXColor c = unk_804230b8;
    c.r = r;
    c.g = g;
    c.b = b;
    c.a = a;
    return c;
}

void effBrokenBarrierDisp(CameraId camId, void* param) {
    effBrokenBarrierData* data;
    CameraEntry* camera;
    EffectEntry* effect;
    Mtx mtx;
    Mtx scale;
    Mtx rot;
    Mtx work;
    Mtx view;
    GXTexObj texObj;
    Vec axis;
    GXColor color;

    camera = camGetPtr(camId);
    effect = param;
    data = effect->userdata;
    PSMTXTrans(mtx, data->x, data->y, data->z);
    PSMTXScale(scale, data->field_0x60, data->field_0x60, data->field_0x60);
    PSMTXConcat(mtx, scale, work);
#ifdef MUST_MATCH
    color = effBrokenBarrierMakeColor(data->field_0x40, data->field_0x44, data->field_0x48,
                                      data->field_0x5C);
#else
    color = unk_804230b8;
    color.r = data->field_0x40;
    color.g = data->field_0x44;
    color.b = data->field_0x48;
    color.a = data->field_0x5C;
#endif
    GXSetTevColor(GX_TEVREG1, color);
    effGetTexObjN64(0x20, &texObj);
    GXLoadTexObj(&texObj, GX_TEXMAP0);
    GXSetNumChans(0);
    GXSetNumTexGens(1);
    GXSetTexCoordGen2(GX_TEXCOORD0, GX_TG_MTX2x4, GX_TG_TEX0, GX_TEXMTX0, GX_FALSE, GX_PTIDENTITY);
    PSMTXScale(scale, float_0p0056818_8041eac0, float_0p045455_8041eac4, float_0_8041eac8);
    GXLoadTexMtxImm(scale, GX_TEXMTX0, GX_MTX2x4);
    GXSetNumTevStages(1);
    GXSetTevOrder(GX_TEVSTAGE0, GX_TEXCOORD0, GX_TEXMAP0, GX_COLOR_NULL);
    GXSetTevColorOp(GX_TEVSTAGE0, GX_TEV_ADD, GX_TB_ZERO, GX_CS_SCALE_1, GX_TRUE, GX_TEVPREV);
    GXSetTevAlphaOp(GX_TEVSTAGE0, GX_TEV_ADD, GX_TB_ZERO, GX_CS_SCALE_1, GX_TRUE, GX_TEVPREV);
    GXSetTevColorIn(GX_TEVSTAGE0, GX_CC_C0, GX_CC_ONE, GX_CC_TEXC, GX_CC_ZERO);
    GXSetTevAlphaIn(GX_TEVSTAGE0, GX_CA_ZERO, GX_CA_A0, GX_CA_TEXA, GX_CA_ZERO);
    GXSetCullMode(GX_CULL_NONE);
    PSMTXConcat(camera->view, work, view);
    main_dl(effect, view);
    axis = vec3_802fa334;
    PSMTXRotAxisRad(rot, &axis, float_2p0944_8041eacc);
    PSMTXConcat(work, rot, view);
    PSMTXConcat(camera->view, view, view);
    main_dl(effect, view);
    PSMTXRotAxisRad(rot, &axis, float_neg2p0944_8041ead0);
    PSMTXConcat(work, rot, view);
    PSMTXConcat(camera->view, view, view);
    main_dl(effect, view);
}

