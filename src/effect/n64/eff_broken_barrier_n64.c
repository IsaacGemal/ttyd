// Layout of one BrokenBarrierN64 particle; the base element (index 0) also
// carries the shared colour whose bytes main_dl caches before the loop.
typedef struct effBrokenBarrierData {
    s32 type;       // 0x0
    f32 x;          // 0x4
    f32 y;          // 0x8
    f32 z;          // 0xC
    f32 spreadX;    // 0x10, half-width of the scatter box (x and z); x4 for types 2 and 3
    f32 spreadY;    // 0x14, scatter height
    f32 velX;       // 0x18, per-frame step, eased toward velTargetX
    f32 velY;       // 0x1C
    f32 velZ;       // 0x20
    f32 velTargetX; // 0x24
    f32 velTargetY; // 0x28
    f32 velTargetZ; // 0x2C
    s32 cycle;      // 0x30, 0..19 (indexes scale_data); negative while waiting to start
    f32 rotZ;       // 0x34, spin in degrees, +4 per frame
    s32 life;       // 0x38
    s32 frame;      // 0x3C, counts up every frame
    u32 baseR;      // 0x40, shared colour from the base element
    u32 baseG;      // 0x44
    u32 baseB;      // 0x48
    s32 alpha;      // 0x4C, fade from life; 0xFF when a particle spawns
    u32 colorR;     // 0x50, particle colour
    u32 colorG;     // 0x54
    u32 colorB;     // 0x58
    u32 baseA;      // 0x5C
    f32 scale;      // 0x60, base: entry scale; particles: scale_data[cycle]
    f32 field_0x64; // 0x64
    f32 field_0x68; // 0x68
} effBrokenBarrierData;


static void main_dl(EffectEntry* effect, Mtx matrix);
EffectEntry* effBrokenBarrierN64Entry(s32 type, s32 life, f32 x, f32 y, f32 z, f32 scale) {
    EffectEntry* entry;
    effBrokenBarrierData* data;
    effBrokenBarrierData* d;
    f32 f6;
    s32 i;

    entry = effEntry();
    entry->type = "BrokenBarrierN64";
    entry->count = 0x3D;
    data = __memAlloc(HEAP_EFFECT, 0x19BC);
    entry->userdata = data;
    entry->callback = effBrokenBarrierMain;
    entry->flags |= 2;
    data->type = type;
    data->frame = 0;
    if (life <= 0) {
        data->life = 1000;
    } else {
        data->life = life;
    }
    d = data + 1;
    data->alpha = 0xff;
    data->x = x;
    data->y = y;
    data->z = z;
    data->scale = scale;
    data->spreadX = 30.0f;
    data->spreadY = 30.0f;
    data->baseR = 0xff;
    data->baseG = 0xff;
    data->baseB = 0xff;
    data->colorR = 0xd7;
    data->colorG = 0xff;
    data->colorB = 0xeb;
    data->baseA = 0xff;
    if (life < 20) {
        f6 = 0.33333334f;
    } else {
        f6 = (f32)life / 60.0f;
    }
    for (i = 1; i < 61; i++, d++) {
        d->cycle = (s32)(-(f32)i * f6) - 1;
    }
    return entry;
}

// Inlined MetroWerks sqrtf (same shape as eff_fire_dust_n64.c / eff_magic3_n64.c).
int __float_nan[];
#define NAN (*(f32*)__float_nan)

#define FP_NAN 1
#define FP_INFINITE 2
#define FP_ZERO 3
#define FP_NORMAL 4
#define FP_SUBNORMAL 5

static inline s32 effBrokenBarrierFpClassify(f32 x) {
    switch (*(s32*)&x & 0x7F800000) {
    case 0x7F800000:
        if (*(s32*)&x & 0x007FFFFF) {
            return FP_NAN;
        }
        else {
            return FP_INFINITE;
        }
    case 0:
        if (*(s32*)&x & 0x007FFFFF) {
            return FP_SUBNORMAL;
        }
        else {
            return FP_ZERO;
        }
    default:
        return FP_NORMAL;
    }
}

#define fpclassify(x) effBrokenBarrierFpClassify(x)
#define isnan(x) (fpclassify(x) == FP_NAN)

static inline f32 effBrokenBarrierSqrt(f32 x) {
    const f64 _half = .5;
    const f64 _three = 3.0;

    if (x > 0.0f) {
        f64 guess = __frsqrte(x);
        guess = _half * guess * (_three - guess * guess * x);
        guess = _half * guess * (_three - guess * guess * x);
        guess = _half * guess * (_three - guess * guess * x);
        return x * guess;
    }
    else if (x < 0.0) {
        return NAN;
    }
    else if (isnan(x)) {
        return NAN;
    }
    return x;
}

// Helper for effBrokenBarrierMain: three Newton-Raphson refinements of __frsqrte with a fresh
// variable per step. Same math as effBrokenBarrierSqrt above; the distinct names are what let the
// caller's trailing `fmul` colour the way the original does.
static inline f32 effBrokenBarrierSqrt2(f32 x) {
    const f64 _half = .5;
    const f64 _three = 3.0;
    if (x > 0.0f) {
        f64 g1 = __frsqrte(x);
        f64 g2 = _half * g1 * (_three - g1 * g1 * x);
        f64 g3 = _half * g2 * (_three - g2 * g2 * x);
        f64 g4 = _half * g3 * (_three - g3 * g3 * x);
        return x * g4;
    }
    else if (x < 0.0) { return NAN; }
    else if (isnan(x)) { return NAN; }
    return x;
}
#pragma opt_lifetimes off // default lifetime analysis coalesces the cos temp into f24; off restores the original f25-f27 colouring
void effBrokenBarrierMain(EffectEntry* effect) {
    s32 rangeX;
    s32 rangeY;
    effBrokenBarrierData* data;
    s32 i;
    s32 type;
    Vec position;
    Vec disp = vec3_802fa328;
    f32 halfX;
    f32 halfY;
    f32 spreadX;
    f32 spreadY;
    f32 c2;
    f32 angle2;
    f32 angle1;
    f32 randA;
    f32 randB;

    data = effect->userdata;
    disp.x = data->x;
    disp.y = data->y;
    disp.z = data->z;
    position = disp;
    type = data->type;

    if (effect->flags & 4) {
        effect->flags &= ~4;
        data->life = 0x10;
    }
    if (data->life < 1000) {
        data->life--;
    }
    data->frame++;
    if (data->life < 0) {
        effDelete(effect);
        return;
    }
    if (data->life < 8) {
        data->alpha = data->life << 5;
    }

    spreadX = data->spreadX;
    spreadY = data->spreadY;
    switch (type) {
    case 2:
    case 3:
        spreadX *= 4.0f;
        spreadY *= 4.0f;
        break;
    }
    i = 1;
#ifdef MUST_MATCH
    /* MUST_MATCH: a literal 0.5f keeps the constant in f1, so rangeX's fctiwz takes f2 and rangeY's
       takes f0 (retail's colouring). The named extern is rematerialised after the first fctiwz, which
       swaps the two; the load and the arithmetic are identical either way. */
    {
    f32 k = 0.5f;
    rangeX = (s32)spreadX;
    halfX = k * spreadX;
    rangeY = (s32)spreadY;
    halfY = k * spreadY;
    }
#else
    rangeX = (s32)spreadX;
    rangeY = (s32)spreadY;
    halfX = 0.5f * spreadX;
    halfY = 0.5f * spreadY;
#endif
    data++;
    for (; i < effect->count; i++, data++) {
        data->cycle++;
        if (data->cycle >= 0x14) {
            data->cycle = 0;
        }
        if (data->cycle < 0) {
            continue;
        }
        if (data->cycle == 0) {
            randA = (f32)(rand() % 360);
            randB = (f32)(rand() % 360);
            switch (type) {
            case 0:
            case 2:
                {
                f32 p;
                angle2 = 6.2831855f * randB / 360.0f;
                c2 = (f32)cos(angle2);
                randA = 6.2831855f * randA / 360.0f;
                p = spreadX * (f32)sin(randA);
                data->x = p * c2;
                c2 = (f32)cos(angle2);
                p = spreadY * (f32)cos(randA);
                data->y = p * c2;
                data->z = spreadX * (f32)sin(angle2);
                }
                data->velX = 0.4f * data->x;
                data->velY = 0.4f * data->y;
                data->velZ = 0.4f * data->z;
                data->velTargetX = 0.1f * data->velX;
                data->velTargetY = 0.1f * data->velY;
                data->velTargetZ = 0.1f * data->velZ;
                break;
            default:
                data->x = (f32)(rand() % rangeX) - halfX;
                data->y = (f32)(rand() % rangeY) - halfY;
                data->z = (f32)(rand() % rangeX) - halfX;
                data->velX = 0.3f * data->x;
                data->velY = 0.3f * data->y;
                data->velZ = 0.3f * data->z;
                data->velTargetX = 0.02f * data->velX;
                data->velTargetY = 0.02f * data->velY;
                data->velTargetZ = 0.02f * data->velZ;
                break;
            }
            data->field_0x64 = (f32)(rand() % 15);
            data->field_0x68 = (f32)(rand() % 15);
            data->rotZ = 0.0f;
            data->alpha = 0xff;
        }
        data->scale = scale_data[data->cycle];
        data->rotZ += 4.0f;
        switch (type) {
        case 2:
        case 3:
            data->velX = 0.05f * -data->x;
            data->velY = 0.05f * -data->y;
            data->velZ = 0.05f * -data->z;
            if (effBrokenBarrierSqrt2(data->velX * data->velX + data->velY * data->velY + data->velZ * data->velZ) < 1.0f) {
                {
                f32 a2, aa, p;
                aa = (f32)(rand() % 360);
                randB = (f32)(rand() % 360);
                a2 = 6.2831855f * randB / 360.0f;
                c2 = (f32)cos(a2);
                aa = 6.2831855f * aa / 360.0f;
                p = spreadX * (f32)sin(aa);
                data->x = p * c2;
                c2 = (f32)cos(a2);
                p = spreadY * (f32)cos(aa);
                data->y = p * c2;
                data->z = spreadX * (f32)sin(a2);
                }
            }
            break;
        }
        data->x += data->velX;
        data->y += data->velY;
        data->z += data->velZ;
        data->field_0x64 += 0.2f;
        data->field_0x68 += 0.6f;
        data->velX += 0.04f * (data->velTargetX - data->velX);
        data->velY += 0.04f * (data->velTargetY - data->velY);
        data->velZ += 0.04f * (data->velTargetZ - data->velZ);
    }
    dispEntry(CAMERA_3D, dispCalcZ(&position), 2, effBrokenBarrierDisp, effect);
}
#pragma opt_lifetimes reset

// Builds the particle colour from the shared zero colour; the inline forces mwcc to
// keep the named GXColor at r1+0x8 and its outgoing copy at r1+0xC (the original order).
static inline GXColor effBrokenBarrierMakeColor(u8 r, u8 g, u8 b, u8 a) {
    GXColor c = unk_804230b8;
    c.r = r;
    c.g = g;
    c.b = b;
    c.a = a;
    return c;
}
void effBrokenBarrierDisp(CameraId camId, void* param) {
    effBrokenBarrierData* data;
    CameraEntry* camera;
    EffectEntry* effect;
    Mtx mtx;
    Mtx scale;
    Mtx rot;
    Mtx work;
    Mtx view;
    GXTexObj texObj;
    Vec axis;
    GXColor color;

    camera = camGetPtr(camId);
    effect = param;
    data = effect->userdata;
    PSMTXTrans(mtx, data->x, data->y, data->z);
    PSMTXScale(scale, data->scale, data->scale, data->scale);
    PSMTXConcat(mtx, scale, work);
#ifdef MUST_MATCH
    color = effBrokenBarrierMakeColor(data->baseR, data->baseG, data->baseB,
                                      data->baseA);
#else
    color = unk_804230b8;
    color.r = data->baseR;
    color.g = data->baseG;
    color.b = data->baseB;
    color.a = data->baseA;
#endif
    GXSetTevColor(GX_TEVREG1, color);
    effGetTexObjN64(0x20, &texObj);
    GXLoadTexObj(&texObj, GX_TEXMAP0);
    GXSetNumChans(0);
    GXSetNumTexGens(1);
    GXSetTexCoordGen2(GX_TEXCOORD0, GX_TG_MTX2x4, GX_TG_TEX0, GX_TEXMTX0, GX_FALSE, GX_PTIDENTITY);
    PSMTXScale(scale, 0.0056818184f, 0.045454547f, 0.0f);
    GXLoadTexMtxImm(scale, GX_TEXMTX0, GX_MTX2x4);
    GXSetNumTevStages(1);
    GXSetTevOrder(GX_TEVSTAGE0, GX_TEXCOORD0, GX_TEXMAP0, GX_COLOR_NULL);
    GXSetTevColorOp(GX_TEVSTAGE0, GX_TEV_ADD, GX_TB_ZERO, GX_CS_SCALE_1, GX_TRUE, GX_TEVPREV);
    GXSetTevAlphaOp(GX_TEVSTAGE0, GX_TEV_ADD, GX_TB_ZERO, GX_CS_SCALE_1, GX_TRUE, GX_TEVPREV);
    GXSetTevColorIn(GX_TEVSTAGE0, GX_CC_C0, GX_CC_ONE, GX_CC_TEXC, GX_CC_ZERO);
    GXSetTevAlphaIn(GX_TEVSTAGE0, GX_CA_ZERO, GX_CA_A0, GX_CA_TEXA, GX_CA_ZERO);
    GXSetCullMode(GX_CULL_NONE);
    PSMTXConcat(camera->view, work, view);
    main_dl(effect, view);
    axis = vec3_802fa334;
    PSMTXRotAxisRad(rot, &axis, 2.0943952f);
    PSMTXConcat(work, rot, view);
    PSMTXConcat(camera->view, view, view);
    main_dl(effect, view);
    PSMTXRotAxisRad(rot, &axis, -2.0943952f);
    PSMTXConcat(work, rot, view);
    PSMTXConcat(camera->view, view, view);
    main_dl(effect, view);
}

// main_dl: build the by-value GXSetTevColor GXColor in an inline so mwcc places the named colour at
// r1+0x8 and its outgoing copy at r1+0xC (a direct build swaps the two stack slots).
#ifdef MUST_MATCH
static inline GXColor effBrokenBarrierBarrierColor(u8 r, u8 g, u8 b, u8 a) {
    GXColor c = unk_804230bc;
    c.r = r;
    c.g = g;
    c.b = b;
    c.a = a;
    return c;
}
#endif
static void main_dl(EffectEntry* effect, Mtx matrix) {
    effBrokenBarrierData* data;
    Mtx mtx, scale, rot;
    s32 c0, c1, c2;
    s32 i;
    effVtxArray* vtx;
    GXColor color;
    f32 alphaScale;
    f32 v;

    data = effect->userdata;
    c0 = data->colorR;
    c1 = data->colorG;
    c2 = data->colorB;
    alphaScale = (f32)data->alpha / 255.0f;
    data++;
    for (i = 1; i < effect->count; i++, data++) {
        if (data->cycle < 0) {
            continue;
        }
        PSMTXTrans(mtx, data->x, data->y, data->z);
        PSMTXRotRad(rot, 'z', 0.017453292f * data->rotZ);
        v = data->scale * alphaScale;
        PSMTXScale(scale, v, v, v);
        PSMTXConcat(mtx, rot, mtx);
        PSMTXConcat(mtx, scale, mtx);
        PSMTXConcat(matrix, mtx, mtx);
        GXLoadPosMtxImm(mtx, GX_PNMTX0);
        GXSetCurrentMtx(GX_PNMTX0);
#ifdef MUST_MATCH
        color = effBrokenBarrierBarrierColor(c0, c1, c2, (u8)((f32)data->alpha * alphaScale));
#else
        color = unk_804230bc;
        color.r = c0;
        color.g = c1;
        color.b = c2;
        color.a = (u8)((f32)data->alpha * alphaScale);
#endif
        GXSetTevColor(GX_TEVREG0, color);
        switch (i & 7) {
            case 0:
                vtx = (effVtxArray*)((u8*)size8x8_tex22x22_vtx + 0xA8);
                break;
            case 1:
                vtx = (effVtxArray*)((u8*)size8x8_tex22x22_vtx + 0xE0);
                break;
            case 2:
                vtx = (effVtxArray*)((u8*)size8x8_tex22x22_vtx + 0x118);
                break;
            case 3:
                vtx = (effVtxArray*)((u8*)size8x8_tex22x22_vtx + 0x150);
                break;
            case 4:
                vtx = (effVtxArray*)((u8*)size8x8_tex22x22_vtx + 0x188);
                break;
            case 5:
                vtx = (effVtxArray*)size8x8_tex22x22_vtx;
                break;
            case 6:
                vtx = (effVtxArray*)((u8*)size8x8_tex22x22_vtx + 0x38);
                break;
            case 7:
                vtx = (effVtxArray*)((u8*)size8x8_tex22x22_vtx + 0x70);
                break;
        }
        effSetVtxDescN64(vtx);
        GXBegin(GX_TRIANGLES, GX_VTXFMT0, 6);
        tri2(0, 1, 2, 0, 0, 2, 3, 0);
    }
}

