void effBoobooMain(EffectEntry* effect) {
	BoobooData* data;
	s32 i;
	BOOL disp;
	s32 counter;

	data = effect->userdata;
	data->timer++;
	for (i = 0; i < 11; i++) {
		counter = data->counter[i];
		disp = FALSE;
		switch (data->state[i]) {
		case 0:
			disp = TRUE;
			break;
		case 1:
			data->poly[i] = 1;
			disp = TRUE;
			break;
		case 3:
			data->poly[i] = anime_data_walk[counter % 8];
			data->rot[i] += (f32)sin(6.2831855f * (counter * 10) / 360.0f);
			if (counter >= 36) {
				data->counter[i] = 0;
				disp = TRUE;
			}
			break;
		case 2:
			data->poly[i] = anime_data_walk[counter % 8];
			data->bob[i] = 2.0f * (f32)sin(6.2831855f * (counter * 20) / 360.0f);
			disp = TRUE;
			if (counter >= 9) {
				data->bob[i] = 0.0f;
				data->counter[i] = 0;
				disp = TRUE;
			}
			break;
		case 4:
			data->poly[i] = anime_data_walk[counter % 8];
			data->bob[i] = 4.0f * (f32)sin(6.2831855f * (counter * 20) / 360.0f);
			if (counter >= 9) {
				data->bob[i] = 0.0f;
				data->counter[i] = 0;
				disp = TRUE;
			}
			break;
		default:
		case 5:
			data->poly[i] = anime_data_walk[counter % 8];
			data->bob[i] = 12.0f * (f32)sin(6.2831855f * (counter * 5) / 360.0f);
			if (counter >= 36) {
				data->bob[i] = 0.0f;
				data->counter[i] = 0;
				disp = TRUE;
			}
			break;
		}
		data->counter[i]++;
		if (disp && (data->flags[i] & 2)) {
			data->flags[i] &= ~2;
			data->state[i] = data->restore[i];
			data->counter[i] = 0;
		}
	}
	dispEntry(CAMERA_3D, 0.0f, 0, effBoobooDisp, effect);
}

