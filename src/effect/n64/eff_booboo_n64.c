// Draws one of the three Booboo shapes. As an inline, `poly` is a front-end temp numbered ahead of the
// loop's pointer temps, which gives the original's callee-saved order (camera, shape, data pointers).
static inline void boo_polygon(int poly) {
	GXSetCullMode(GX_CULL_BACK);
	switch (poly) {
	case 0:
		boo_polygon_0();
		break;
	case 1:
		boo_polygon_1();
		break;
	case 2:
		boo_polygon_2();
		break;
	}
}

// Storing the sin result in `f32 s` first pools 6.2832/360 before 63.0 as the original's .sdata2 does.
void effBoobooDisp(CameraId camId, void* param) {
	EffectEntry* effect = param;
	CameraEntry* camera;
	int phase;
	BoobooData* data;
	int i;
	Mtx mtx;
	Mtx scaleMtx;
	Mtx rotMtx;

	camera = camGetPtr(camId);
	data = effect->userdata;
	phase = data->timer * 30;
	for (i = 0; i < 11; i++, phase += 20) {
		if (data->flags[i] & 1) {
			PSMTXTrans(mtx, data->x[i], data->y[i] + data->bob[i], data->z[i]);
			PSMTXRotRad(rotMtx, 'y', 0.017453292f * (180.0f - data->rot[i]));
			PSMTXConcat(mtx, rotMtx, mtx);
			PSMTXScale(scaleMtx, 10.0f, 10.0f, 10.0f);
			PSMTXConcat(mtx, scaleMtx, mtx);
			PSMTXConcat(camera->view, mtx, mtx);
			GXLoadPosMtxImm(mtx, GX_PNMTX0);
			GXSetCurrentMtx(GX_PNMTX0);
			if (!texture_dl(param, i, data->tex[i])) {
				if (data->tex[i] == 8 || data->tex[i] == 9) {
					f32 s = (f32)sin(6.2831855f * phase / 360.0f);
					u8 bright = (u8)(63.0f + 63.0f * s);
					GXSetTevColor(GX_TEVREG0, (GXColor){ bright, bright, bright, 0 });
				}
				boo_polygon(data->poly[i]);
			}
		}
	}
}
