// clang-format off
EffectEntry* effIceEntry(s32 type, s32 count, f32 x, f32 y, f32 z, f32 scale) {
	EffectEntry* effect;
	IceData* data;

	effect = effEntry();
	effect->type = "Ice";
	effect->count = 1;
	data = __memAlloc(HEAP_EFFECT, 0x30);
	effect->userdata = data;
	effect->callback = effIceMain;
	effect->flags |= 2;
	data->type = type;
	data->x = x;
	data->y = y;
	data->z = z;
	data->scale = scale;
	data->scaleX = 1.0f;
	data->scaleY = 1.0f;
	data->scaleZ = 1.0f;
	if (count > 0) {
		data->timer = count;
	} else {
		data->timer = 0x3E8;
	}
	data->frame = 0;
	data->state = 0;
	data->anim = effMayaAnimAlloc(ice_effAnimDt);
	effPlayMayaAnim(data->anim);
	return effect;
}


// effIceMain is local to this file in the original object (.fn effIceMain, local).
static void effIceMain(EffectEntry* effect) {
	Vec pos;
	Vec disp = { 0 };
	OSTime time;
	u64 msecPerFrame;
	IceData* data = effect->userdata;

	disp.x = data->x;
	disp.y = data->y;
	disp.z = data->z;
	pos = disp;

	if (effect->flags & 4) {
		effect->flags &= ~4;
		data->frame = 90;
		data->state = 1;
		if (gp->inBattle != 0) {
			time = gp->renderTime;
		} else {
			time = gp->renderFieldTime;
		}
		msecPerFrame = (u64)(1000.f / (f32)gp->framerate);
		data->anim->time = OSTicksToMilliseconds(time) - msecPerFrame * data->frame;
	}

	switch (data->state) {
	case 0:
		if (data->timer < 1000) {
			data->timer--;
		}
		if (data->timer == 0) {
			data->state = 1;
		}
		if (data->frame < 90) {
			data->frame++;
			effCalcMayaAnim(data->anim);
		}
		break;
	case 1:
		data->frame++;
		effCalcMayaAnim(data->anim);
		break;
	case 2:
		data->frame++;
		if (data->frame % 30 == 0) {
			f32 argx = data->x + (f32)(20 - irand((s32)(40.f * data->scale)));

			effKemuTestEntry(1, argx,
				data->y - 30.f * (1.0f - data->scaleY), data->z, 1.0f);
		}
		data->scaleY *= 0.99f;
		data->scaleX *= 1.005f;
		data->scaleZ *= 0.99f;
		break;
	}

	switch (data->state) {
	case 0:
	case 1:
		if ((f32)data->frame > data->anim->animData->unk04) {
			effDeleteMayaAnim(data->anim);
			effDelete(effect);
			return;
		}
		break;
	case 2:
		if (data->frame > 200) {
			effDeleteMayaAnim(data->anim);
			effDelete(effect);
			return;
		}
		break;
	}

	dispEntry(CAMERA_3D, dispCalcZ(&pos), 2, effIceDisp, effect);
}


// effIceDisp is local to this file in the original object (.fn effIceDisp, local).
static void effIceDisp(CameraId cameraId, void* param) {
	EffectEntry* effect = param;
	IceData* data = effect->userdata;
	GXTexObj texObj;
	Mtx mtxA;
	Mtx mtxB;
	Mtx mtxC;
	Mtx mtxD;
	Mtx mtxE;
	s32 i;

	PSMTXTrans(mtxA, data->x, data->y, data->z);
	PSMTXRotRad(mtxB, 'y', -camGetPtr(cameraId)->viewYaw * 0.017453292f);
	PSMTXConcat(mtxA, mtxB, mtxC);
	PSMTXTrans(mtxA, 0.0f, -30.f, 0.0f);
	PSMTXConcat(mtxC, mtxA, mtxC);
	PSMTXScale(mtxD, data->scaleX, data->scaleY, 1.0f);
	PSMTXConcat(mtxC, mtxD, mtxC);
	PSMTXTrans(mtxA, 0.0f, 30.f, 0.0f);
	PSMTXConcat(mtxC, mtxA, mtxC);
	PSMTXScale(mtxD, 8.0f * data->scale, 8.0f * data->scale, 8.0f * data->scale);
	PSMTXConcat(mtxC, mtxD, mtxC);

	GXSetNumChans(1);
	GXSetChanCtrl(GX_COLOR0A0, GX_FALSE, GX_SRC_REG, GX_SRC_REG, GX_LIGHT_NULL, GX_DF_NONE, GX_AF_NONE);
	GXSetNumTexGens(1);
	GXSetTexCoordGen2(GX_TEXCOORD0, GX_TG_MTX2x4, GX_TG_TEX0, GX_IDENTITY, GX_FALSE, GX_PTIDENTITY);
	GXSetNumTevStages(1);
	GXSetTevOrder(GX_TEVSTAGE0, GX_TEXCOORD0, GX_TEXMAP0, GX_COLOR0A0);
	GXSetTevOp(GX_TEVSTAGE0, GX_MODULATE);
	GXSetCurrentMtx(0);

	for (i = 1; i < data->anim->animData->rstData->count; i++) {
		s32 texId = 0x20;

		if (i < data->anim->animData->rstData->count - 1) {
			texId = 0x1F;
		}
		effGetTexObj(texId, &texObj);
		GXLoadTexObj(&texObj, GX_TEXMAP0);
		if (i < data->anim->animData->rstData->count - 1) {
			effGetTexObj(0x1F, &texObj);
			GXLoadTexObj(&texObj, GX_TEXMAP0);
			GXSetChanMatColor(GX_COLOR0A0, (GXColor){ 0xFF, 0xFF, 0xFF, (u8)(s32)(191.25f * data->scaleZ) });
		} else {
			effGetTexObj(0x20, &texObj);
			GXLoadTexObj(&texObj, GX_TEXMAP0);
			GXSetChanMatColor(GX_COLOR0A0, (GXColor){ 0xFF, 0xFF, 0xFF, (u8)(s32)(127.5f * data->scaleZ) });
		}
		PSMTXConcat(mtxC, data->anim->entries[0].mtx, mtxE);
		PSMTXConcat(mtxE, data->anim->entries[i].mtx, mtxE);
		PSMTXConcat(camGetPtr(cameraId)->view, mtxE, mtxE);
		GXLoadPosMtxImm(mtxE, 0);
		effDrawMayaPoly(&data->anim->animData->rstData->entries[i]);
	}
}

