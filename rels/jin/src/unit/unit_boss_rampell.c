// Functions are emitted by MWCC in reverse source order, so they are written here
// reversed (_mario_makkuro_set, vivian_comeback, eff_scanning) to keep .text in the
// original order _mario_makkuro_set, vivian_comeback, eff_scanning.
static USER_FUNC(eff_scanning) {
    s32* args;
    s32 id;
    f32 x;
    f32 y;
    f32 z;
    BattleUnit* unit;
    EffectEntry* entry;

    args = event->args;
    id = BattleTransID(event, evtGetValue(event, args[0]));
    x = evtGetFloat(event, args[1]);
    y = evtGetFloat(event, args[2]);
    z = evtGetFloat(event, args[3]);
    unit = BattleGetUnitPtr(_battleWorkPointer, id);
    entry = effScanningEntry(0, x, y, z);
    *(f32*)((u8*)entry->userdata + 0x10) = unit->mSizeMultiplier;
    return EVT_RETURN_DONE;
}

static s32 vivian_comeback(void) {
    pouchGetPtr()->partyData[PARTNER_VIVIAN].flags &= ~2;
    return 1;
}

static USER_FUNC(_mario_makkuro_set) {
    BattleWork* work;
    BattleUnit* unit;

    work = _battleWorkPointer;
    unit = BattleGetUnitPtr(work, BattleTransID(event, -2));
    if (unit != NULL) {
        faker_mario_makkuro_set();
        animPoseSetMaterialFlagOn(*(s32*)BtlUnit_GetPartsPtr(unit, 1)->field_0x1C0, 0xB000000);
    }
    return EVT_RETURN_DONE;
}

